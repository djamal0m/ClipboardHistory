import SwiftUI

/// User-facing appearance override. `.system` (the default) follows the
/// Mac's current Light/Dark setting automatically; the other two pin the
/// app's own windows regardless of the system-wide setting.
enum AppAppearance: String, CaseIterable, Identifiable {
    case system
    case light
    case dark

    var id: String { rawValue }

    var label: String {
        switch self {
        case .system: return "System"
        case .light: return "Light"
        case .dark: return "Dark"
        }
    }

    var colorScheme: ColorScheme? {
        switch self {
        case .system: return nil
        case .light: return .light
        case .dark: return .dark
        }
    }
}
